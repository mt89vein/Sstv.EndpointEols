using Microsoft.Extensions.DependencyInjection;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace Sstv.EndpointEol.Swashbuckle;

/// <summary>
/// Extension methods that add end-of-life annotations to a Swagger/OpenAPI document.
/// </summary>
public static class SwaggerGenOptionsExtensions
{
    /// <summary>
    /// Registers <see cref="EndOfLifeOperationFilter"/> and <see cref="EndOfLifeDocumentFilter"/>.
    /// The method is idempotent: filters already registered manually are not added twice.
    /// </summary>
    /// <param name="options">Swagger generation options.</param>
    /// <returns>The same options instance for chaining.</returns>
    public static SwaggerGenOptions AddEndOfLifeAnnotations(this SwaggerGenOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);

        if (!options.OperationFilterDescriptors.Any(static descriptor => descriptor.Type == typeof(EndOfLifeOperationFilter)))
        {
            options.OperationFilter<EndOfLifeOperationFilter>();
        }

        if (!options.DocumentFilterDescriptors.Any(static descriptor => descriptor.Type == typeof(EndOfLifeDocumentFilter)))
        {
            options.DocumentFilter<EndOfLifeDocumentFilter>();
        }

        return options;
    }
}

/// <summary>
/// Extension methods for <see cref="IServiceCollection"/> that wire end-of-life annotations
/// into Swashbuckle.
/// </summary>
public static class ServiceCollectionExtensions
{
    /// <summary>
    /// Adds end-of-life annotations to every Swagger document generated by the application.
    /// Call it next to <c>AddSwaggerGen()</c>; the order of the two calls does not matter.
    /// </summary>
    /// <param name="services">Service registrator.</param>
    /// <returns>Service registrator.</returns>
    public static IServiceCollection AddEndOfLifeSwagger(this IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);

        services.PostConfigure<SwaggerGenOptions>(static options => options.AddEndOfLifeAnnotations());

        return services;
    }
}
